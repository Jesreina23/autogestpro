/**
 * Normaliza el nombre de una marca automotriz para generar su clave de categoria
 * Ejemplo: "Chevrolet" -> "MODELO_CHEVROLET"
 * Ejemplo: "Empire Keeway" -> "MODELO_EMPIRE_KEEWAY"
 * Ejemplo: "United Motors" -> "MODELO_UNITED_MOTORS"
 */
export function getCategoriaModelo(marca: string): string {
  const norm = marca
    .trim()
    .toUpperCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^A-Z0-9]/g, "_");
  return `MODELO_${norm}`;
}
